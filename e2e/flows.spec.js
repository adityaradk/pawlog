import { test, expect } from '@playwright/test'

const iso = (offset) => {
  const d = new Date()
  d.setDate(d.getDate() + offset)
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
}

const shot = (page, info, name) =>
  page.screenshot({ path: `docs/screenshots/${info.project.name}-${name}.png`, fullPage: true })

async function signInDemo(page) {
  await page.goto('./#/signin')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await page.getByRole('button', { name: 'Continue with demo account' }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Alex')
}

const group = (page, tone) => page.locator(`section[aria-labelledby="group-${tone}"]`)

test('sign in and dashboard shows overdue, today and upcoming', async ({ page }, info) => {
  await page.goto('./#/signin')
  await page.evaluate(() => localStorage.clear())
  await page.goto('./#/weight')
  await expect(page).toHaveURL(/#\/signin/) // protected route redirects
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByText('Enter an email address')).toBeVisible()
  await shot(page, info, '01-signin')
  await page.getByRole('button', { name: 'Continue with demo account' }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Alex')
  for (const tone of ['overdue', 'today', 'upcoming']) {
    await expect(group(page, tone).locator('.item').first()).toBeVisible()
  }
  await expect(group(page, 'overdue')).toContainText('FVRCP booster')
  await expect(group(page, 'today')).toContainText('Ear drops')
  await shot(page, info, '02-dashboard')
})

test('flow 1: vet visit with follow-up reminder', async ({ page }, info) => {
  await signInDemo(page)
  await page.getByRole('link', { name: 'Add vet visit or vaccine' }).click()
  await page.getByRole('button', { name: 'Save vet visit' }).click()
  await expect(page.getByText('Enter the reason for the visit')).toBeVisible()
  await page.getByLabel('Reason for visit').fill('Ear check')
  await page.getByLabel(/^Clinic/).fill('Prairie Paws Veterinary Clinic')
  await page.getByLabel(/^Notes/).fill('Left ear still a little red. Continue drops.')
  await page.getByLabel(/^Weight at this visit/).fill('4.7')
  await page.getByText('Create a follow-up reminder').click()
  await page.getByLabel('What needs to happen?').fill('Recheck ears')
  await page.getByLabel('Due date').fill(iso(-1))
  await page.getByRole('button', { name: 'Save vet visit' }).click()
  await expect(page.getByText('This date has already passed')).toBeVisible()
  await page.getByLabel('Due date').fill(iso(21))
  await shot(page, info, '03-record-form')
  await page.getByRole('button', { name: 'Save vet visit' }).click()
  const toast = page.locator('.toast').first()
  await expect(toast).toContainText('Vet visit saved · Follow-up “Recheck ears” added for')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Ear check')
  await shot(page, info, '04-record-detail')
  await toast.getByRole('link', { name: 'View task' }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Recheck ears')
  await expect(page.getByText('Created from')).toBeVisible()
  await shot(page, info, '05-task-detail')
  await page.locator('.facts').getByRole('link', { name: /Vet visit,/ }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Ear check')

  // Timeline filter + delete with linked follow-up warning
  await page.goto('./#/timeline')
  await page.getByRole('button', { name: /^Vaccinations/ }).click()
  await expect(page.locator('.tl-item')).toHaveCount(1)
  await page.getByRole('button', { name: /^All/ }).click()
  await shot(page, info, '06-timeline')
  await page.getByRole('link', { name: 'Ear check' }).click()
  await page.getByRole('button', { name: 'Delete' }).click()
  await expect(page.getByRole('dialog')).toContainText('linked follow-up')
  await shot(page, info, '07-delete-dialog')
  await page.getByRole('button', { name: 'Cancel' }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
})

test('flow 2: give and dismiss medication doses', async ({ page }, info) => {
  await signInDemo(page)
  const today = group(page, 'today')
  const doses = today.locator('.item', { hasText: 'Ear drops' })
  await expect(doses).toHaveCount(2)
  await doses.first().getByRole('button', { name: 'Mark as given' }).click()
  await expect(page.locator('.toast').first()).toContainText('recorded as given')
  await expect(doses).toHaveCount(1)
  // Undo brings it back, then give again
  await page.locator('.toast').first().getByRole('button', { name: 'Undo' }).click()
  await expect(doses).toHaveCount(2)
  await doses.first().getByRole('button', { name: 'Mark as given' }).click()
  await expect(doses).toHaveCount(1)
  await doses.first().getByRole('button', { name: 'Dismiss' }).click()
  await expect(page.locator('.toast').last()).toContainText('NOT recorded as given')
  await expect(doses).toHaveCount(0)
  await shot(page, info, '08-dashboard-after-doses')
  await page.goto('./#/medications')
  await page.getByRole('link', { name: 'Dose history' }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Ear drops')
  const history = page.locator('.history')
  await expect(history.getByText('Dismissed – not recorded as given').first()).toBeVisible()
  await expect(history.getByText('Missed – not given').first()).toBeVisible()
  // Exactly one log per dose: today shows one Given and one Dismissed
  await expect(page.locator('section[aria-labelledby="today-doses"] .badge-given')).toHaveCount(1)
  await expect(page.locator('section[aria-labelledby="today-doses"] .badge-dismissed')).toHaveCount(1)
  await shot(page, info, '09-dose-history')
  await page.goto('./#/medications/new')
  await page.getByRole('button', { name: 'Save medication' }).click()
  await expect(page.getByText('Enter the medication name')).toBeVisible()
  await shot(page, info, '10-medication-form-errors')
})

